static const uint8_t *glyph_for(char c)
{
    if (c < FONT_FIRST || c > FONT_LAST)
        c = FONT_FIRST; // blank glyph

    return font[c - FONT_FIRST];
}

void gfx_put_pixel(uint32_t x, uint32_t y, uint32_t color)
{
    const struct framebuffer_info *fb = framebuffer_get_info();
    if (!fb || fb->addr == 0 || x >= fb->width || y >= fb->height)
        return;

    uint8_t *row = (uint8_t *)fb->addr + y * fb->pitch;
    ((uint32_t *)row)[x] = color;
}

void gfx_fill_rect(uint32_t x, uint32_t y, uint32_t w, uint32_t h, uint32_t color)
{
    for (uint32_t row = 0; row < h; row++)
        for (uint32_t col = 0; col < w; col++)
            gfx_put_pixel(x + col, y + row, color);
}

void gfx_draw_char(uint32_t x, uint32_t y, char c, uint32_t fg, uint32_t bg)
{
    const uint8_t *glyph = glyph_for(c);

    for (uint32_t row = 0; row < FONT_GLYPH_SIZE; row++)
        for (uint32_t col = 0; col < FONT_GLYPH_SIZE; col++)
            gfx_put_pixel(x + col, y + row, (glyph[row] & (0x80 >> col)) ? fg : bg);
}

void gfx_draw_string(uint32_t x, uint32_t y, const char *str, uint32_t fg, uint32_t bg)
{
    uint32_t cursor_x = x;

    for (; *str; str++)
    {
        if (*str == '\n')
        {
            cursor_x = x;
            y += FONT_GLYPH_SIZE;
            continue;
        }

        gfx_draw_char(cursor_x, y, *str, fg, bg);
        cursor_x += FONT_GLYPH_SIZE;
    }
}
